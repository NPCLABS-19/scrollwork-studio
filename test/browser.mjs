import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, stat } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const base = process.env.SCROLLWORK_TEST_URL || 'http://127.0.0.1:4317';
await mkdir('.impeccable/review', { recursive: true });
try {
  await page.goto(base);
  await page.locator('.specimen').last().waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.locator('.specimen').count(), 9);
  const original = await page.locator('.specimen').first().locator('path').first().getAttribute('d');
  await page.getByRole('button', { name: 'Lock motif for next sheet' }).first().click();
  await page.getByRole('button', { name: /New sheet/ }).click();
  assert.equal(await page.locator('.specimen').first().locator('path').first().getAttribute('d'), original, 'locked motif survives');
  await page.getByRole('button', { name: 'Save selected motif', exact: true }).click();
  await page.getByRole('button', { name: /Saved motifs/ }).click();
  assert.equal(await page.locator('.specimen').count(), 1);
  await page.locator('.specimen-main').click();
  const weight = page.getByRole('slider', { name: 'Line weight', exact: true });
  await weight.fill('6.2');
  assert.equal(await page.locator('.inspector-preview path[fill="none"]').first().getAttribute('stroke-width'), '6.2');
  await page.getByLabel('Construction guides & drag handles').check();
  assert.equal(await page.locator('.geometry-handles circle').count(), 4);
  await page.getByLabel('Construction guides & drag handles').uncheck();
  let downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: /Export motif/ }).click();
  let dl = await downloadPromise;
  await dl.saveAs('.impeccable/review/exported-motif.svg');
  assert.ok((await stat('.impeccable/review/exported-motif.svg')).size > 1000);
  downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export sheet', exact: true }).click();
  dl = await downloadPromise;
  await dl.saveAs('.impeccable/review/exported-sheet.svg');
  downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export sheet as PNG' }).click();
  dl = await downloadPromise;
  await dl.saveAs('.impeccable/review/exported-sheet.png');
  assert.ok((await stat('.impeccable/review/exported-sheet.png')).size > 10_000);
  await page.getByRole('button', { name: 'Repeat study' }).click();
  assert.equal(await page.locator('.specimen').count(), 9);
  await page.getByLabel('Alternate rotation').check();
  assert.ok((await page.locator('.specimen .motif').nth(3).getAttribute('style')).includes('180deg'));
  await page.getByRole('button', { name: 'Open original reference archive' }).click();
  assert.equal(await page.locator('.specimen').count(), 10);
  assert.ok((await page.locator('.trace-info').innerText()).includes('source-mask overlap'));
  await page.getByRole('checkbox', { name: 'Overlay thresholded source' }).check();
  assert.equal(await page.locator('.source-overlay').count(), 1);
  await page.locator('input[type=file]').setInputFiles('public/references/spindle.jpg');
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button', { name: 'Trace selected region' }).click();
  await page.getByRole('button', { name: 'Add motif to catalogue' }).waitFor();
  await page.waitForFunction(() => !document.querySelector('.import-dialog footer button').disabled);
  assert.ok((await page.locator('.trace-result').innerText()).includes('source-mask overlap'));
  const overlapText = await page.locator('.trace-result > span').innerText();
  assert.ok(parseFloat(overlapText.match(/([\d.]+)%/)[1]) >= 95, 'browser trace preserves the reference silhouette and holes');
  await page.getByRole('button', { name: 'Add motif to catalogue' }).click();
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.locator('.specimen').count(), 11);
  await page.locator('input[type=file]').setInputFiles({ name: 'inherited-stroke.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="none" stroke-width="7"><g transform="translate(2 3)"><path d="M10 10 C 20 80 80 80 90 10"/></g></svg>') });
  await page.locator('.motif-title h2').filter({ hasText: 'inherited-stroke' }).waitFor();
  assert.equal(await page.locator('.inspector-preview path').first().getAttribute('fill'), 'none', 'SVG inherited fill is preserved');
  assert.equal(await page.locator('.inspector-preview path').first().getAttribute('stroke-width'), '7', 'SVG inherited line weight is preserved');
  downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  dl = await downloadPromise;
  await dl.saveAs('.impeccable/review/roundtrip-project.json');
  await page.getByRole('button', { name: /New sheet/ }).click();
  await page.locator('input[type=file]').setInputFiles('.impeccable/review/roundtrip-project.json');
  await page.waitForFunction(() => document.querySelectorAll('.specimen').length === 12);
  assert.equal(await page.locator('.specimen').count(), 12, 'project roundtrip restores imports');
  await page.locator('input[type=file]').setInputFiles('public/references/catalogue.jpg');
  const cropFrame = page.locator('.crop-frame');
  await page.waitForFunction(() => document.querySelector('.crop-frame img')?.naturalWidth > 0);
  const rect = await cropFrame.boundingBox();
  await page.mouse.move(rect.x + rect.width * (35 / 678), rect.y + rect.height * (10 / 840));
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * (230 / 678), rect.y + rect.height * (190 / 840), { steps: 8 });
  await page.mouse.up();
  await page.getByRole('spinbutton', { name: 'Crop left (%)' }).fill('5');
  await page.getByRole('spinbutton', { name: 'Crop top (%)' }).fill('1');
  await page.getByRole('spinbutton', { name: 'Crop width (%)' }).fill('29');
  await page.getByRole('spinbutton', { name: 'Crop height (%)' }).fill('22');
  await page.getByRole('button', { name: 'Trace selected region' }).click();
  await page.waitForFunction(() => !document.querySelector('.import-dialog footer button').disabled);
  const cropViewBox = await page.locator('.trace-result .motif').getAttribute('viewBox');
  assert.ok(Number(cropViewBox.split(' ')[2]) < 220, 'crop selects one motif rather than tracing the entire catalogue');
  await page.getByRole('button', { name: 'Add motif to catalogue' }).click();
  await page.reload();
  assert.equal(await page.locator('.specimen').count(), 13, 'catalogue restores locally');
  await page.getByRole('button', { name: /Saved motifs/ }).click();
  assert.equal(await page.locator('.specimen').count(), 1, 'saved motif restores locally');
  await page.getByRole('button', { name: /Catalogue/ }).click();
  await page.getByRole('button', { name: /New sheet/ }).click();
  await page.getByRole('button', { name: 'Endless exploration' }).click();
  const seedBefore = await page.getByRole('textbox', { name: 'Sheet seed' }).inputValue();
  await page.waitForFunction(before => document.querySelector('#seed').value !== before, seedBefore, { timeout: 8000 });
  await page.getByRole('button', { name: 'Pause exploration' }).click();
  assert.equal(await page.getByRole('button', { name: 'Endless exploration' }).getAttribute('aria-pressed'), 'false');
  // Reset only this isolated browser context for the first visual inspection.
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'mobile layout does not overflow');
  await page.setViewportSize({ width: 320, height: 760 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, '320px layout does not overflow');
  assert.deepEqual(errors, [], 'no browser runtime errors');
  console.log('PASS: generation, locking, editing, guides, saving, restore, SVG/PNG export, exact repeat, archive, import/trace, endless mode, desktop/mobile rendering.');
} finally { await browser.close(); }
